export const DICT = { pt, en, es, de };

export function t(key, params) {
  const lang = getSettings().lang;
  let s = (DICT[lang] && DICT[lang][key]) || pt[key] || key;
  if (params) Object.keys(params).forEach((k) => { s = s.split(`{${k}}`).join(String(params[k])); });
  return s;
}

